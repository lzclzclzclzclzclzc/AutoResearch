def result(step, output, did="discussion:group-v3"):
    return {"protocol_version": 2, "next_step": step, "final_output": output,
        "discussion_id": did, "decision_source": "god"}


@pytest.mark.asyncio
async def test_critic_returns_to_new_exploration_then_delivers_exact_plan_without_summary(engine):
    runtime, project = engine
    store, rid = runtime.store, project["id"]
    cycle = store.put("cycle", "cycle", {"line_id": "line-01", "objective": "objective"}, rid)
    store.update_line(rid, "line-01", cycle_id=cycle["id"])
    state = {"research_id": rid, "line_id": "line-01", "task_id": "line-task", "cycle_id": "cycle", "direction_epoch": 1, "revision": 1}
    calls = []
    async def discuss(research_id, did, role, members, context, line_id):
        calls.append((did, role, context))
        if len(calls) == 1:
            return result("critic", {"content_markdown": "first design"}, did + ":group-v3")
        if len(calls) == 2:
            return result("exploration", {"content_markdown": "God selected a different study"}, did + ":group-v3")
        if len(calls) == 3:
            assert context["critic_handoff"]["content_markdown"] == "God selected a different study"
            return result("critic", {"content_markdown": "revised design"}, did + ":group-v3")
        return result("implementation", {"content_markdown": "Use this exact final plan", "experiment_spec": {
            "question": "Can it work?", "fixed": {"seed": 73}, "metrics": ["accuracy"],
            "issues": [{"issue_id": "historical", "category": "must_fix", "description": "retained old disagreement"}]}}, did + ":group-v3")
    runtime.discussions.run = discuss
    async def forbidden(*args, **kwargs):
        pytest.fail("Accepted final products must never be regenerated by another model")
    runtime.turn = forbidden
    output = await runtime.design(state)
    spec = store.get("spec", output["spec_id"])
    assert spec["fixed"] == {"seed": 73} and spec["discussion_protocol"] == 2
    assert [role for _, role, _ in calls] == ["exploration", "critic", "exploration", "critic"]
    assert calls[2][0] != calls[0][0] and calls[3][0] != calls[1][0]
    handoff = store.get("discussion_handoff", calls[3][0] + ":group-v3")
    assert handoff["status"] == "delivered" and handoff["spec_id"] == output["spec_id"]
    assert not store.get("discussion_handoff", calls[3][0])


@pytest.mark.asyncio
async def test_design_shares_raw_verifications_from_all_line_cycles_only(engine):
    runtime, project = engine
    store, rid = runtime.store, project["id"]
    for cycle_id, epoch in (("old-cycle-1", 1), ("old-cycle-2", 2), ("current-cycle", 3)):
        store.put("cycle", cycle_id, {"line_id": "line-01", "objective": "historical evidence",
            "direction_epoch": epoch, "completed_verify_rounds": 1, "k": 3}, rid)
    store.update_line(rid, "line-01", cycle_id="current-cycle", direction_epoch=3, completed_verify_rounds=1)
    evidence_path = store.data_dir / "folds.csv"
    evidence_path.write_text("fold,accuracy\n1,0.8\n", encoding="utf-8")
    artifact = store.register_artifact(rid, evidence_path, "text/csv",
        line_id="line-01", cycle_id="old-cycle-1")
    reports = []
    for report_id, cycle_id, passed in (("old-verify-1", "old-cycle-1", False),
            ("old-verify-2", "old-cycle-2", True), ("current-verify", "current-cycle", False)):
        # Persist the legacy report shape: cycle_id is its only line association.
        reports.append(store.put("verification", report_id, {"cycle_id": cycle_id, "passed": passed,
            "content_markdown": f"{report_id}: inspect folds.csv artifact_id={artifact['id']}",
            "source_ids": [artifact["id"]], "evidence": [{"artifact_id": artifact["id"]}],
            "discussion_id": f"{report_id}:verify-discussion", "round_no": 1}, rid))
    store.put("cycle", "other-line-cycle", {"line_id": "line-02", "objective": "unrelated line"}, rid)
    store.put("verification", "other-line-verify", {"cycle_id": "other-line-cycle",
        "passed": True, "content_markdown": "other line evidence"}, rid)
    other_rid = store.create_project({"topic": "other project", "mode": "demo",
        "client_request_id": "other-project"})["id"]
    store.put("cycle", "other-project-cycle", {"line_id": "line-01", "objective": "unrelated project"}, other_rid)
    store.put("verification", "other-project-verify", {"cycle_id": "other-project-cycle",
        "passed": True, "content_markdown": "other project evidence"}, other_rid)
    before_reports = store.list("verification")
    before_cycles = store.list("cycle")
    contexts = {}

    async def discuss(research_id, did, role, members, context, line_id):
        contexts[role] = context
        if role == "exploration":
            return result("critic", {"content_markdown": "design using historical evidence"}, did + ":group-v3")
        return result("implementation", {"content_markdown": "final plan",
            "experiment_spec": {"question": "Does the historical result apply?",
                "fixed": {"seed": 73}, "metrics": ["accuracy"]}}, did + ":group-v3")

    runtime.discussions.run = discuss
    output = await runtime.design({"research_id": rid, "line_id": "line-01",
        "task_id": "history-task", "cycle_id": "current-cycle", "direction_epoch": 3, "revision": 1})

    assert set(contexts) == {"exploration", "critic"}
    for context in contexts.values():
        visible = {report["id"]: report for report in context["previous_verifications"]}
        assert set(visible) == {"old-verify-1", "old-verify-2", "current-verify"}
        assert visible == {report["id"]: report for report in reports}
        assert all("line_id" not in report for report in visible.values())
    assert store.list("verification") == before_reports
    assert store.list("cycle") == before_cycles
    assert store.get("line", f"{rid}:line-01")["completed_verify_rounds"] == 1
    assert store.get("spec", output["spec_id"])["question"] == "Does the historical result apply?"


@pytest.mark.asyncio
async def test_boss_mixed_operations_reuse_active_work_and_apply_once(engine):
    runtime, project = engine
    rid, store = project["id"], runtime.store
    lines = store.lines(rid)
    context = {"lines": lines}
    initial = result("dispatch", {"content_markdown": "start both", "operations": [
        {"operation": "research", "target": line["line_id"], "objective": "initial objective"} for line in lines]})
    await runtime.apply_discussion_boss({"id": "initial", "research_id": rid, "payload": {}}, initial, context)
    active = next(task for task in store.list("task", rid) if task.get("kind") == "line" and task["payload"]["line_id"] == "line-01")
    mixed = result("dispatch", {"content_markdown": "continue A, end B, report", "operations": [
        {"operation": "research", "target": "研究线 1", "objective": "additional context"},
        {"operation": "finish_line", "target": "line-02"}, {"operation": "report"}]}, "mixed:group-v3")
    store.put("discussion_handoff", "mixed:group-v3", {"status": "pending"}, rid)
    task = {"id": "mixed", "research_id": rid, "payload": {}}
    await runtime.apply_discussion_boss(task, mixed, {"lines": store.lines(rid)})
    count = len(store.list("task", rid))
    await runtime.apply_discussion_boss(task, mixed, {"lines": store.lines(rid)})
    assert len(store.list("task", rid)) == count
    assert len(store.list("cycle", rid)) == 2
    assert store.get("task", active["id"])["status"] == "pending"
    assert store.get("boss_operation", "mixed:operation:0")["effect"]["status"] == "reused"
    assert store.get("line", f"{rid}:line-02")["finish_requested"]
    assert store.get("discussion_handoff", "mixed:group-v3")["status"] == "delivered"
    reports = [task for task in store.list("task", rid) if task["kind"] == "paper"]
    assert len(reports) == 1
    snapshot = store.get("report_snapshot", reports[0]["payload"]["snapshot_id"])["snapshot"]
    assert snapshot["arrangements"][2]["status"] == "applying"
    assert "待办" in snapshot["notice"]


@pytest.mark.asyncio
async def test_boss_direction_change_closes_old_task_before_new_epoch(engine):
    runtime, project = engine
    rid, store = project["id"], runtime.store
    context = {"lines": store.lines(rid)}
    task = {"research_id": rid, "id": "first", "payload": {}}
    await runtime.apply_discussion_boss(task, result("dispatch", {"content_markdown": "start",
        "operations": [{"operation": "research", "target": "line-01", "objective": "old objective"}]}), context)
    old = next(task for task in store.list("task", rid) if task["kind"] == "line")
    change = result("dispatch", {"content_markdown": "change", "operations": [
        {"operation": "change_direction", "target": "line-01", "objective": "new objective"}]})
    await runtime.apply_discussion_boss({**task, "id": "changed"}, change, {"lines": store.lines(rid)})
    assert store.get("task", old["id"])["status"] == "cancelled"
    line = store.get("line", f"{rid}:line-01")
    assert line["direction_epoch"] == 2 and not line["finish_requested"]
    assert store.get("cycle", line["cycle_id"])["objective"] == "new objective"


@pytest.mark.asyncio
async def test_boss_partial_failure_retries_only_unfinished_effects(engine, monkeypatch):
    runtime, project = engine
    rid, store = project["id"], runtime.store
    discussion = result("dispatch", {"content_markdown": "research and report", "operations": [
        {"operation": "research", "target": "line-01", "objective": "execute once"}, {"operation": "report"}]}, "partial:group-v3")
    task = {"research_id": rid, "id": "partial", "payload": {}}
    original, calls, fail = store.apply_boss_effects, [], True
    def effects(research_id, key, *args):
        nonlocal fail
        calls.append(key)
        if key == "partial:operation:1" and fail:
            fail = False
            raise ConnectionError("report service temporarily unavailable")
        return original(research_id, key, *args)
    monkeypatch.setattr(store, "apply_boss_effects", effects)
    with pytest.raises(ConnectionError):
        await runtime.apply_discussion_boss(task, discussion, {"lines": store.lines(rid)})
    assert store.get("boss_operation", "partial:operation:0")["status"] == "applied"
    assert store.get("boss_operation", "partial:operation:1")["status"] == "failed"
    assert any(message.get("operation_status") == "failed" for message in store.messages("partial:group-v3")["items"])
    await runtime.apply_discussion_boss(task, discussion, {"lines": store.lines(rid)})
    assert calls.count("partial:operation:0") == 1 and calls.count("partial:operation:1") == 2
    assert len(store.list("cycle", rid)) == 1
    assert len([task for task in store.list("task", rid) if task["kind"] == "paper"]) == 1


def test_boss_conflicting_operations_fail_before_side_effects():
    lines = [{"line_id": "line-01", "title": "A", "cycle_id": "active"}]
    with pytest.raises(ValueError, match="冲突"):
        normalize_operations({"operations": [{"operation": "research", "target": "A"},
            {"operation": "finish_line", "target": "A"}]}, "dispatch", lines)
    assert normalize_operations({"operations": [{"operation": "report"}, {"operation": "report"}]}, "dispatch", lines) == [{"operation": "report"}]


def test_new_verification_ignores_old_issue_gate_but_requires_real_evidence(tmp_path):
    store = Store(tmp_path)
    rid = store.create_project({"topic": "evidence", "mode": "demo", "client_request_id": "evidence"})["id"]
    path = tmp_path / "result.txt"
    path.write_text("observed negative result")
    artifact = store.register_artifact(rid, path, line_id="line-01")
    submission = {"spec": {"discussion_protocol": 2, "issues": [
        {"issue_id": "old", "category": "must_fix", "acceptance_stage": "execution", "resolved": False}]},
        "artifacts": [artifact], "run": {"state": "completed"}}
    verification = {"passed": True, "scientific_observation": "negative", "evidence": [
        {"source_id": artifact["id"], "status": "negative"}]}
    validate_execution_checks(store, rid, submission, verification, "line-01")
    submission["run"]["state"] = "execution_failed"
    with pytest.raises(ValueError, match="failed experiment"):
        validate_execution_checks(store, rid, submission, verification, "line-01")
